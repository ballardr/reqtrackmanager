"""
Module: scripts.seed_repo_demo

Seeds the "ReqTrackManager (this product)" demo project: this repository's own requirements, decisions, SOC 2
assessment, known gaps and architecture principles, loaded from the committed fixture `data/repo_demo.json`
(generated by `extract_repo_demo.py`, which a test keeps in step with the documents).

Responsibilities:
- Create one project in the demo organisation and everything in it through the real HTTP API, using the helpers of
  `seed_demo_data` (same convention as the other seeds, so the usual validation, versioning and audit apply).
- Be idempotent by skipping: a second run finds the project and changes nothing.

Design decisions:
- Decisions attributed to the user, and the original design choices, are Approved; decisions the implementing
  agent made for the user to veto wait Under review, which is what the log says about them.
- Requirements for the Ossa and Pelion versions, which the decisions log records as implemented, are completed;
  Massif requirements are Approved; the rest stay Draft.
- Open known gaps become Risks; they are loaded by default because the policies are public in the repository
  (`--skip-gaps` leaves them out of a seed).

External dependencies: `httpx` and the helpers of `seed_demo_data`.

Run from `tests/container` (after `seed_demo_data.py`, which also calls it):
    docker compose exec backend python scripts/seed_repo_demo.py
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import httpx
import seed_demo_data as base

FIXTURE_PATH = Path(__file__).resolve().parent / "data" / "repo_demo.json"
PROJECT_NAME = "ReqTrackManager (this product)"
WORKFLOW_NAME = "Release horizon"
FIRST_PHASE = "Planned"
# The versions the decisions log records as built, and the stage phase each version reaches.
COMPLETED_TARGETS = {"Ossa (v1)", "Pelion (v2)"}
APPROVED_TARGETS = {"Massif (v3)"}
STAGE_PHASE = {"Ossa (v1)": "Released", "Pelion (v2)": "Released", "Massif (v3)": "Building", "Murchison (v4)": "Planned"}


def load_fixture() -> dict:
    """Reads the committed demo fixture.

    Returns:
        The fixture dictionary.

    Raises:
        FileNotFoundError: If the fixture has not been generated.
    """
    return json.loads(FIXTURE_PATH.read_text(encoding="utf-8"))


def seed_requirements(headers: dict, org_id: str, project: dict, fixture: dict) -> int:
    """Creates the components, categories, requirements and the version stages.

    Args:
        headers: Authorization headers of the project manager.
        org_id: The organisation's id.
        project: The created project.
        fixture: The demo fixture.

    Returns:
        The number of requirements created.
    """
    project_id = project["id"]
    components: dict[str, dict] = {}
    categories: dict[tuple[str, str], dict] = {}
    for component in fixture["components"]:
        created = base.create_component(headers, project_id, component["name"], component["prefix"])
        components[component["name"]] = created
        for category in component["categories"]:
            categories[(component["name"], category["name"])] = base.create_category(
                headers, project_id, created["id"], category["name"], category["prefix"]
            )
    stage_workflow = base.create_org_workflow(headers, org_id, WORKFLOW_NAME, [
        (FIRST_PHASE, "open"), ("Building", "open"), ("Review", "review"), ("Released", "closed"),
    ])
    stages = {stage["name"]: base.create_stage(headers, project_id, stage["name"], stage_workflow["id"]) for stage in fixture["stages"]}
    for spec in fixture["requirements"]:
        description = f"Source requirement {spec['source_id']} in docs/requirements.md.\n\n{spec['statement']}".strip()
        if spec["description"]:
            description += f"\n\n{spec['description']}"
        requirement = base.create_requirement(
            headers, project_id, name=spec["name"], reasoning=spec["reasoning"] or "Not stated in the source document.",
            description=description, component_id=components[spec["component"]]["id"],
            category_id=categories[(spec["component"], spec["category"])]["id"],
        )
        if spec["target"] in COMPLETED_TARGETS | APPROVED_TARGETS:
            requirement = base.set_requirement_status(headers, project_id, requirement, "approved")
        if spec["target"] in COMPLETED_TARGETS:
            base.complete_requirement(headers, project_id, requirement["id"])
        base.tag_record(headers, project_id, "requirement", requirement["id"], [spec["level"], spec["target"]])
    for name, phase in STAGE_PHASE.items():
        # A new stage starts in the workflow's first phase.
        if name in stages and phase != FIRST_PHASE:
            base.transition_stage(headers, project_id, stages[name]["id"], phase)
    return len(fixture["requirements"])


def seed_decisions(headers: dict, project_id: str, fixture: dict, owner_id: str) -> int:
    """Creates the decisions and walks each to the state its attribution implies.

    Args:
        headers: Authorization headers of the project manager.
        project_id: The project's id.
        fixture: The demo fixture.
        owner_id: The user who owns every decision.

    Returns:
        The number of decisions created.
    """
    types = base.list_decision_types(headers, project_id)
    for decision in fixture["decisions"]:
        record = base.create_decision(
            headers, project_id, title=decision["title"], decision_statement=decision["statement"],
            decision_type_id=types[decision["type"]]["id"], owner_id=owner_id, rationale=decision["rationale"],
            context=f"Recorded in docs/decisions.md under \"{decision['section']}\".",
        )
        attribution = decision["decided_by"]
        if attribution:
            base.tag_record(headers, project_id, "decision", record["id"], [f"Decided by {attribution}"])
        if attribution == "Agent":
            base.advance_decision_to_review(headers, project_id, record["id"])
        else:
            base.propose_and_approve_decision(headers, project_id, record["id"], approval_comment="Recorded in the decisions log.")
    return len(fixture["decisions"])


def seed_compliance(headers: dict, org_id: str, project_id: str, fixture: dict) -> int:
    """Creates the SOC 2 standard, assigns it to the project, assesses each criterion and records the policies as evidence.

    Args:
        headers: Authorization headers of the project manager.
        org_id: The organisation's id.
        project_id: The project's id.
        fixture: The demo fixture.

    Returns:
        The number of criteria assessed.
    """
    standard_spec = fixture["standard"]
    standard = base.create_compliance_standard(
        headers, org_id, reference=standard_spec["reference"], name=standard_spec["name"],
        description=standard_spec["description"], issuing_organisation="AICPA",
    )
    version = base.list_compliance_versions(headers, org_id, standard["id"])[0]
    reference_ids: dict[str, str] = {}
    for group in standard_spec["groups"]:
        parent = base.create_compliance_requirement(
            headers, org_id, standard["id"], version["id"], name=group["name"], reference=group["reference"],
            reasoning=f"Criteria group {group['reference']} of the Trust Services Criteria.",
        )
        reference_ids[group["reference"]] = parent["id"]
        for criterion in group["criteria"]:
            child = base.create_compliance_requirement(
                headers, org_id, standard["id"], version["id"], name=criterion["name"], reference=criterion["reference"],
                description=f"{criterion['control']}\n\nEvidence: {criterion['evidence']}",
                reasoning=f"Criterion {criterion['reference']} of the Trust Services Criteria.",
                parent_requirement_id=parent["id"],
            )
            reference_ids[criterion["reference"]] = child["id"]
    base.publish_compliance_version(headers, org_id, standard["id"], version["id"])
    assignment = base.assign_compliance_standard(headers, org_id, project_id, standard["id"], version["id"])
    by_requirement = {pcr["requirement_id"]: pcr["id"] for pcr in base.list_compliance_requirements(headers, project_id, assignment["id"])}
    assessed = 0
    pcr_by_policy: dict[str, list[str]] = {}
    for group in standard_spec["groups"]:
        for criterion in group["criteria"]:
            pcr_id = by_requirement[reference_ids[criterion["reference"]]]
            base.update_compliance_assessment(
                headers, project_id, assignment["id"], pcr_id, compliance_status=criterion["status"],
                justification=criterion["status_note"] if criterion["status"] == "non_compliant" else "",
                notes=criterion["status_note"],
            )
            assessed += 1
            for policy in criterion["policies"]:
                pcr_by_policy.setdefault(policy, []).append(pcr_id)
    for policy in fixture["policies"]:
        base.create_compliance_evidence(
            headers, project_id, title=policy["title"],
            notes=f"docs/soc2/policies/{policy['file']}.md", pcr_ids=pcr_by_policy.get(policy["file"], []),
        )
    return assessed


def seed_risks_and_principles(headers: dict, project_id: str, fixture: dict, owner_id: str, include_gaps: bool) -> tuple[int, int]:
    """Creates a risk for each open known gap and a guiding principle for each architecture principle.

    Args:
        headers: Authorization headers of the project manager.
        project_id: The project's id.
        fixture: The demo fixture.
        owner_id: The user who owns every record.
        include_gaps: Whether the known gaps are loaded as risks.

    Returns:
        The number of risks and of guiding principles created.
    """
    risks = 0
    if include_gaps:
        risk_types = base.list_effective_risk_types(headers, project_id)
        levels = base.get_risk_levels(headers, project_id)
        for gap in fixture["gaps"]:
            base.create_risk(
                headers, project_id, levels, risk_type_id=risk_types[gap["type"]]["id"],
                owner={"type": "user", "id": owner_id}, title=gap["title"], statement=gap["statement"],
                risk_event=f"Known gap in docs/soc2/policies/{gap['policy']}.md",
            )
            risks += 1
    for principle in fixture["principles"]:
        record = base.create_project_guiding_principle(
            headers, project_id, name=principle["name"], principle_statement=principle["statement"],
            rationale="Core Architecture Principles in docs/solution-architecture.md.", priority="high",
            owner={"type": "user", "id": owner_id},
        )
        base.propose_and_approve_project_guiding_principle(
            headers, project_id, record["id"], approval_comment="Recorded in the architecture document.",
        )
    return risks, len(fixture["principles"])


def seed_repo_demo(
    headers: dict, org: dict, *, admin_user_id: str, member_user_ids: list[str], include_gaps: bool = True,
) -> dict | None:
    """Creates the project of this product's own records in the demo organisation, unless it already exists.

    Args:
        headers: Authorization headers of the organisation administrator, who becomes project manager.
        org: The demo organisation.
        admin_user_id: The administrator's user id (owner of every record).
        member_user_ids: Other demo users, each given the stakeholder role so every demo account sees the project.
        include_gaps: Whether open known gaps are loaded as risks.

    Returns:
        Counts of what was created, or None when the project already existed.

    Raises:
        httpx.HTTPStatusError: If any API call is refused.
    """
    existing = httpx.get(f"{base.BASE}/projects", headers=headers, params={"organization_id": org["id"], "search": PROJECT_NAME}, timeout=30).json()
    if any(project["name"] == PROJECT_NAME for project in existing):
        print(f"{PROJECT_NAME!r} already exists. Skipping.")
        return None
    fixture = load_fixture()
    for module_key in ("decisions", "context_strategy", "risk_management"):
        base.enable_module(headers, org["id"], module_key)
    print(f"Creating {PROJECT_NAME!r}...")
    project = base.create_project(
        headers, org["id"], PROJECT_NAME,
        "This product's own requirements, decisions, SOC 2 assessment and architecture principles, loaded from its repository documents.",
        report_name="ReqTrackManager",
    )
    for user_id in member_user_ids:
        base.assign_project_role(headers, project["id"], user_id, "stakeholder")
    print("  Requirements, stages...")
    counts = {"requirements": seed_requirements(headers, org["id"], project, fixture)}
    print("  Decisions (this takes a few minutes)...")
    counts["decisions"] = seed_decisions(headers, project["id"], fixture, admin_user_id)
    print("  SOC 2 standard, assessments, evidence...")
    counts["criteria"] = seed_compliance(headers, org["id"], project["id"], fixture)
    print("  Risks, guiding principles...")
    counts["risks"], counts["principles"] = seed_risks_and_principles(headers, project["id"], fixture, admin_user_id, include_gaps)
    return counts


def main(argv: list[str] | None = None) -> int:
    """Seeds the project into an organisation already created by `seed_demo_data`.

    Args:
        argv: Command-line arguments (`--skip-gaps`).

    Returns:
        0 on success, 1 when the demo organisation does not exist.
    """
    parser = argparse.ArgumentParser(description="Seed the project of this product's own records.")
    parser.add_argument("--skip-gaps", action="store_true", help="Do not load the SOC 2 known gaps as risks.")
    args = parser.parse_args(argv)
    h_admin = base.h(base.login(base.ADMIN_EMAIL, base.ADMIN_PASSWORD))
    org = next((o for o in httpx.get(f"{base.BASE}/orgs", headers=h_admin, timeout=30).json() if o["name"] == base.ORG_NAME), None)
    if org is None:
        print(f"Organisation {base.ORG_NAME!r} not found; run seed_demo_data.py first.", file=sys.stderr)
        return 1
    token = base.login("demo.admin@example.com", base.PASSWORD)
    headers = base.h(token)
    users = {u["email"]: u for u in httpx.get(f"{base.BASE}/orgs/{org['id']}/users", headers=headers, timeout=30).json()}
    counts = seed_repo_demo(
        headers, org, admin_user_id=users["demo.admin@example.com"]["user_id"],
        member_user_ids=[users[email]["user_id"] for email in ("demo.engineer@example.com", "demo.stakeholder@example.com")],
        include_gaps=not args.skip_gaps,
    )
    if counts:
        print("Done: " + ", ".join(f"{count} {name}" for name, count in counts.items()))
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except httpx.HTTPStatusError as exc:
        print(f"Request failed: {exc.request.method} {exc.request.url} -> {exc.response.status_code} {exc.response.text}", file=sys.stderr)
        raise
