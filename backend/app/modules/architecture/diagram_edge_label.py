"""
Module: modules.architecture.diagram_edge_label

The text written beside a block diagram's line.

Responsibilities:
- Give a line's label from the connections behind it: their names (when the diagram shows connection names), then the type
  and protocol text that connection detail adds, or the count of a merged line.

Design decisions:
- **One rule, two implementations.** `diagramLines.ts` (`edgeLabelText`) is the browser's port, so the editor shows a line's
  label before it is saved; `diagramLabelCases.json` holds the cases both must give (regenerated by
  `test_architecture_diagram_edge_label.py` with `UPDATE_SHAPE_CASES=1`).
- **Only a named connection adds a line.** A connection with no name adds nothing (its code is not a name); up to
  `NAME_LINES_MAX` names are written, in code order, then "+N more". A name is one line of text: its whitespace is collapsed
  and one longer than `NAME_LINE_MAX` characters is cut with an ellipsis, so a line's label stays a readable size on the screen
  and in the exports.
- **A merged line keeps its count.** With connection detail off the label is only the names, so a merged line ends with its
  `×N` as it would have been drawn without the names.

Dependencies: none.
"""

from __future__ import annotations

from collections.abc import Iterable

#: The most connection names written beside one line; the rest are counted ("+2 more").
NAME_LINES_MAX = 3

#: The longest a written name may be before it is cut with an ellipsis.
NAME_LINE_MAX = 60


def _name_lines(names: Iterable[str]) -> list[str]:
    """The lines for a line's connection names.

    Args:
        names: The names of the connections behind the line, in the order to write them (blank ones are ignored).

    Returns:
        At most `NAME_LINES_MAX` name lines and, when more are named, a final "+N more" line; empty when none is named.
    """
    named = [" ".join(name.split()) for name in names]
    named = [name for name in named if name]
    shown = [name if len(name) <= NAME_LINE_MAX else name[: NAME_LINE_MAX - 1] + "…" for name in named[:NAME_LINES_MAX]]
    if len(named) > NAME_LINES_MAX:
        shown.append(f"+{len(named) - NAME_LINES_MAX} more")
    return shown


def detail_text(count: int, type_name: str | None, protocol: str) -> str | None:
    """The type and protocol text connection detail adds to a line.

    Args:
        count: How many connections the line stands for.
        type_name: The connections' shared type, or `None` when they differ.
        protocol: The connections' shared protocol, or blank.

    Returns:
        `Type · protocol` for one connection (either part alone when the other is missing, `None` when both are), and
        `Type ×N` (`N connections` when the types differ) for several.
    """
    if count == 1:
        return f"{type_name} · {protocol}" if type_name and protocol else (type_name or protocol or None)
    return f"{type_name} ×{count}" if type_name else f"{count} connections"


def edge_label(count: int, type_name: str | None, protocol: str, *, detail: bool, names: Iterable[str] = ()) -> str | None:
    """The label of a line.

    Args:
        count: How many connections the line stands for.
        type_name: The connections' shared type, or `None` when they differ.
        protocol: The connections' shared protocol, or blank.
        detail: Whether the diagram shows connection detail (types and protocols).
        names: The connection names to write, in code order; empty when the diagram does not show connection names.

    Returns:
        The label, one line per `\\n`: the names, then the detail text; `None` when there is nothing to write (the client
        then shows only the count of a merged line).
    """
    parts = _name_lines(names)
    if detail:
        text = detail_text(count, type_name, protocol)
        if text:
            parts.append(text)
    elif parts and count > 1:
        parts.append(f"×{count}")
    return "\n".join(parts) or None
