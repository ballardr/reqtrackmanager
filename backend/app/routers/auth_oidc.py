"""
Module: routers.auth_oidc

The OIDC login flow (E-U-01): redirects the browser to an organisation's identity provider, then on
callback verifies the ID token, provisions or resolves the local user, redeems any pending invite
(services/invites.py), syncs the org role from IdP claims (services/oidc_provisioning.py) and issues the
same kind of access token as native login, so an SSO session is indistinguishable from a native one
(token_version revocation, WebSocket expiry checks and so on apply unchanged).

Not shaped as an `AuthBackend` (app/auth_backends/base.py): that protocol is a single request/response
call, whereas OIDC is a multi-step redirect flow.
"""

from __future__ import annotations

from urllib.parse import quote
from uuid import UUID

from fastapi import APIRouter, Depends, HTTPException, Query, status
from fastapi.responses import RedirectResponse
from sqlalchemy import select
from sqlalchemy.orm import Session

from app.config import get_settings
from app.database import get_db
from app.deps import get_client_ip
from app.models.organization import Organization
from app.security import create_access_token, create_oidc_state_token, decode_access_token
from app.services import credential_reset, oidc_client
from app.services.audit import log_event, log_login
from app.services.invites import consume_pending_invites
from app.services.oidc_provisioning import (
    find_or_provision_user,
    meets_required_group,
    sync_org_groups_from_claims,
    sync_org_roles_from_claims,
)

router = APIRouter(prefix="/api/v1/auth/oidc", tags=["auth-oidc"])
settings = get_settings()


def _redirect_uri() -> str:
    return f"{settings.public_backend_url.rstrip('/')}/api/v1/auth/oidc/callback"


def _get_sso_org_by_slug(db: Session, slug: str) -> Organization:
    org = db.scalar(select(Organization).where(Organization.slug == slug))
    if org is None or not org.sso_enabled or not org.oidc_issuer_url or not org.oidc_client_id:
        raise HTTPException(status.HTTP_404_NOT_FOUND, "SSO is not configured for this organisation.")
    return org


@router.get("/{slug}/login")
def start_oidc_login(
    slug: str,
    client_nonce: str = Query(..., min_length=16, max_length=256),
    client: str = Query("app", pattern="^(app|mcp)$"),
    request_ip: str = Depends(get_client_ip),
    db: Session = Depends(get_db),
):
    """Redirects the browser to the organisation's identity provider to begin login (the "Sign in with
    SSO" target).

    `client_nonce`: generated by the caller and stored in its `sessionStorage` before it navigates here,
    round-tripped through `state` and the callback redirect so the landing page can prove the token
    belongs to this browser's own login attempt (see `security.create_oidc_state_token`).

    `client`: `"app"` (default, the frontend's `/login/{slug}` page) or `"mcp"` (`mcp-server`'s `/login`
    page) selects which of two fixed, server-configured URLs `oidc_callback` redirects back to; restricted
    to these values by the `pattern` validation, never an arbitrary caller-supplied redirect target.
    """
    credential_reset.enforce_oidc_start_rate_limit(request_ip)
    org = _get_sso_org_by_slug(db, slug)
    if org.oidc_issuer_url is None or org.oidc_client_id is None:  # `_get_sso_org_by_slug` has already refused this
        raise HTTPException(status.HTTP_404_NOT_FOUND, "SSO is not configured for this organisation.")
    org_id, issuer_url, client_id = str(org.id), org.oidc_issuer_url, org.oidc_client_id
    db.rollback()  # the network call below can take seconds on a host the tenant chose: do not hold a connection for it
    try:
        discovery = oidc_client.discover(issuer_url)
    except ValueError:
        raise HTTPException(status.HTTP_502_BAD_GATEWAY, "The identity provider is unavailable.") from None
    state = create_oidc_state_token(org_id, client_nonce, client=client)
    authorize_url = oidc_client.build_authorize_url(
        discovery, client_id=client_id, redirect_uri=_redirect_uri(), state=state,
    )
    return RedirectResponse(authorize_url, status_code=status.HTTP_302_FOUND)


@router.get("/callback")
def oidc_callback(code: str, state: str, request_ip: str = Depends(get_client_ip), db: Session = Depends(get_db)):
    """Completes login: exchanges the authorization code, verifies the ID token, checks the org's
    required-group access gate (if configured), provisions or resolves the user, syncs their org role and
    redirects to the frontend with an access token. If the gate rejects the claims it redirects with an
    error message and issues no token.

    Every attempt (failed exchange or verification, required-group denial, success) is recorded as a
    `login_events` row, as native `/login` does, so SSO logins appear in the same authentication-monitoring
    trail.
    """
    state_claims = decode_access_token(state)
    if (
        not state_claims
        or state_claims.get("purpose") != "oidc_state"
        or "org_id" not in state_claims
        or not state_claims.get("client_nonce")
    ):
        raise HTTPException(status.HTTP_401_UNAUTHORIZED, "Invalid or expired SSO login attempt.")
    client_nonce = state_claims["client_nonce"]
    # Only "app" or "mcp" (enforced by `start_oidc_login`'s Query pattern before the token was signed); the
    # fallback is defence in depth, not a trust boundary. Targets are fixed and never derived from caller input.
    if state_claims.get("client") == "mcp":
        redirect_base = settings.mcp_server_public_url.rstrip("/") + "/login/oidc/complete"
    else:
        redirect_base = settings.frontend_base_url.rstrip("/") + "/oidc-complete"
    org = db.get(Organization, UUID(state_claims["org_id"]))
    if org is None or not org.sso_enabled or not org.oidc_issuer_url or not org.oidc_client_id:
        raise HTTPException(status.HTTP_401_UNAUTHORIZED, "SSO is not configured for this organisation.")

    try:
        discovery = oidc_client.discover(org.oidc_issuer_url)
        tokens = oidc_client.exchange_code_for_tokens(
            discovery, client_id=org.oidc_client_id, client_secret=org.oidc_client_secret or "",
            redirect_uri=_redirect_uri(), code=code,
        )
        claims = oidc_client.verify_id_token(
            discovery, tokens["id_token"], client_id=org.oidc_client_id, issuer_url=org.oidc_issuer_url,
        )
    except (KeyError, ValueError) as exc:
        log_login(
            db, user_id=None, email_attempted=f"(oidc login failed: {org.slug})", ip_address=request_ip, success=False, kind="sso"
        )
        db.commit()
        raise HTTPException(status.HTTP_401_UNAUTHORIZED, f"SSO login failed: {exc}") from exc

    if not meets_required_group(org, claims):
        # Authenticated at the IdP but not admitted: refused before any account is provisioned or token
        # issued. A stricter gate than `sync_org_roles_from_claims`, which only decides which role is given.
        log_event(db, entity_type="organization", entity_id=org.id, action="oidc_login_denied_not_provisioned",
                  actor_id=None, organization_id=org.id, detail={"subject": claims.get("sub"), "email": claims.get("email")})
        log_login(
            db, user_id=None, email_attempted=claims.get("email") or "(unknown)", ip_address=request_ip, success=False, kind="sso"
        )
        db.commit()
        message = f"{org.name} has not provisioned you access."
        return RedirectResponse(
            f"{redirect_base}?error=not_provisioned&message={quote(message)}&client_nonce={quote(client_nonce)}",
            status_code=status.HTTP_302_FOUND,
        )

    try:
        user = find_or_provision_user(db, claims, issuer=org.oidc_issuer_url, org=org)
    except ValueError:
        # The claims name an account this IdP may not sign in as (`oidc_provisioning._assert_may_link`) or
        # carry no usable email. The audit row omits the address and reason (which would reveal to an
        # organisation administrator whether an address has an account elsewhere); the browser gets the same
        # message as a required-group refusal.
        db.rollback()
        log_event(db, entity_type="organization", entity_id=org.id, action="oidc_login_denied_link_refused",
                  actor_id=None, organization_id=org.id, detail={"subject": claims.get("sub")})
        log_login(db, user_id=None, email_attempted=claims.get("email") or "(unknown)", ip_address=request_ip, success=False, kind="sso")
        db.commit()
        message = f"{org.name} has not provisioned you access."
        return RedirectResponse(
            f"{redirect_base}?error=not_provisioned&message={quote(message)}&client_nonce={quote(client_nonce)}",
            status_code=status.HTTP_302_FOUND,
        )
    if not user.is_active or user.is_archived:
        # Native login rejects a deactivated, banned or archived user; OIDC applies the same check before
        # `consume_pending_invites`/`sync_org_roles_from_claims` run, so no new role grant is committed for a
        # rejected login (it would otherwise sit unused until the account is reactivated).
        log_event(db, entity_type="user", entity_id=user.id, action="oidc_login_denied_inactive",
                  actor_id=None, organization_id=org.id)
        log_login(db, user_id=user.id, email_attempted=user.email, ip_address=request_ip, success=False, kind="sso")
        db.commit()
        message = "This account has been deactivated."
        return RedirectResponse(
            f"{redirect_base}?error=account_inactive&message={quote(message)}&client_nonce={quote(client_nonce)}",
            status_code=status.HTTP_302_FOUND,
        )
    # Pending invites are redeemed before `sync_org_roles_from_claims`, so an org's SSO group-claim mapping
    # stays the later word on any role it also manages (services/invites.py). `consume_pending_invites` is a
    # no-op for a row pre-provisioned by an sso_only-org invite (`provision_sso_invite`), which has no PendingInvite.
    consume_pending_invites(db, user)
    sync_org_roles_from_claims(db, user, org, claims)
    sync_org_groups_from_claims(db, user, org, claims)
    log_event(db, entity_type="user", entity_id=user.id, action="oidc_login",
              actor_id=user.id, organization_id=org.id, detail={"issuer": org.oidc_issuer_url})
    log_login(db, user_id=user.id, email_attempted=user.email, ip_address=request_ip, success=True, kind="sso")
    db.commit()

    app_token = create_access_token(str(user.id), token_version=user.token_version)
    # The access token travels in the URL fragment, not the query string: fragments are not sent to the
    # server or proxies and do not reach access logs. `client_nonce` rides alongside so OidcCompletePage can
    # confirm the redirect matches this browser's own login attempt (see `security.create_oidc_state_token`).
    return RedirectResponse(
        f"{redirect_base}#token={quote(app_token)}&client_nonce={quote(client_nonce)}",
        status_code=status.HTTP_302_FOUND,
    )
