"""
Module: storage_backends.local

Local filesystem file storage backend — the default, simplest self-host
path (I-M-10). Keys are relative paths under a configured base directory;
nested directories are created automatically.
"""

from __future__ import annotations

import os
from pathlib import Path


class LocalFileStorageBackend:
    """Stores files as plain files under a base directory."""

    name = "local"

    def __init__(self, base_dir: str) -> None:
        self._base_dir = Path(base_dir)
        self._base_dir.mkdir(parents=True, exist_ok=True)

    def _confine(self, key: str) -> str:
        """Resolves `key` to an absolute path confined to the base directory.

        `key` is generated by app/services/files.py, which sanitizes the client-supplied filename (`_safe_key_component`) so it
        cannot contain `/` or traversal segments; the checks here are defence in depth.

        The guard rejects the content of `key` itself before any path is built from it, then confines the path with
        `os.path.commonpath(...)`, which takes no computed-expression argument (CodeQL's `py/path-injection` flags the
        `startswith(base + os.sep)` and `Path.resolve()` shapes).

        `save` repeats the same checks inline immediately before its filesystem write, because CodeQL does not treat a check
        inside a called helper as a sanitizing barrier for the caller's later use of the returned value; `read` and `delete` are
        not flagged (the query models writes as the sink), so they use this helper.

        Raises:
            ValueError: If `key` contains a traversal/absolute-path segment, or the resolved path escapes the base directory.
        """
        if not key or os.path.isabs(key) or "\\" in key or any(
            segment in ("", ".", "..") for segment in key.split("/")
        ):
            raise ValueError("Invalid storage key.")
        base = os.path.realpath(self._base_dir)
        candidate = os.path.realpath(os.path.join(base, key))
        if os.path.commonpath([base, candidate]) != base:
            raise ValueError("Invalid storage key.")
        return candidate

    def save(self, key: str, data: bytes) -> None:
        if not key or os.path.isabs(key) or "\\" in key or any(
            segment in ("", ".", "..") for segment in key.split("/")
        ):
            raise ValueError("Invalid storage key.")
        base = os.path.realpath(self._base_dir)
        candidate = os.path.realpath(os.path.join(base, key))
        if os.path.commonpath([base, candidate]) != base:
            raise ValueError("Invalid storage key.")
        path = Path(candidate)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)

    def read(self, key: str) -> bytes:
        path = Path(self._confine(key))
        if not path.is_file():
            raise FileNotFoundError(key)
        return path.read_bytes()

    def delete(self, key: str) -> None:
        path = Path(self._confine(key))
        path.unlink(missing_ok=True)

    def exists(self, key: str) -> bool:
        """Whether a file is stored under `key`.

        Raises:
            ValueError: If `key` is not a valid storage key (see `_confine`).
        """
        return Path(self._confine(key)).is_file()

    def disk_usage_percent(self) -> float:
        """Returns the percentage of disk space used on the storage volume (I-M-11)."""
        import shutil

        usage = shutil.disk_usage(self._base_dir)
        return (usage.used / usage.total) * 100
